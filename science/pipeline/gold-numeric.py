"""Generate the numeric gold set (data/case/gold/numeric.jsonl) from the bundle catalog. Nothing is typed by hand.

Usage: python -I gold-numeric.py <bundles_dir> <out.jsonl>
One item per stored measurement value of every Item of every bundle in catalog.json: bundle ID, collection SHA-256,
period ID, metric, value, unit, period status and the Item's SHA-256. A withheld value (status not available, or
value null) is not an item. The first line is a header with the catalog's SHA-256. Used by the numeric provenance
suite: a number in model text must equal one of these values for the cited bundle and period.
"""
import datetime
import hashlib
import json
import os
import sys

bundles, out = sys.argv[1:3]


def sha(p):
    return hashlib.sha256(open(p, "rb").read()).hexdigest()


cat_path = os.path.join(bundles, "catalog.json")
cat = json.load(open(cat_path))
items, by_bundle = [], {}
for link in sorted((l for l in cat["links"] if l["rel"] == "child"), key=lambda l: l["href"]):
    cpath = os.path.normpath(os.path.join(bundles, link["href"]))
    col = json.load(open(cpath))
    bid = col["id"]
    for il in sorted((l for l in col["links"] if l["rel"] == "item"), key=lambda l: l["href"]):
        ipath = os.path.normpath(os.path.join(os.path.dirname(cpath), il["href"]))
        it = json.load(open(ipath))
        p = it["properties"]
        for m in p.get("siterra:measurements", []):
            if m.get("value") is None or m.get("status") != "available":
                continue
            by_bundle[bid] = by_bundle.get(bid, 0) + 1
            items.append({"record": "item", "id": f"gn-{bid}-{it['id']}-{m['metric']}", "bundle_id": bid,
                          "collection_sha256": sha(cpath), "collection_version": col.get("version"),
                          "period_id": it["id"], "metric": m["metric"], "value": m["value"], "unit": m.get("unit"),
                          "period_status": p.get("siterra:period_status"), "item_sha256": sha(ipath)})
created = datetime.datetime.now().astimezone().isoformat(timespec="seconds")
header = {"record": "header", "gold_set": "numeric", "version": 1, "catalog": "data/bundles/catalog.json", "catalog_sha256": sha(cat_path),
          "source": "generated by code from every Item measurement in the catalog; withheld values are not items",
          "items": len(items), "items_by_bundle": by_bundle, "created": created}
with open(out, "w") as o:
    for rec in [header] + items:
        o.write(json.dumps(rec) + "\n")
print(len(items), "items;", by_bundle)
